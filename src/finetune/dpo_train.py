"""
DPO Training Script (Direct Preference Optimization)

Reads DPO preference pairs (generated by ``src/mcp_server/dpo_pipeline.py``)
and performs preference optimisation fine-tuning on a base LLM.

This mirrors the structure of ``train.py`` but uses TRL's ``DPOTrainer``
instead of ``SFTTrainer``.

Usage::

    # Run with default pairs path:
    python src/finetune/dpo_train.py

    # Custom pairs path:
    python src/finetune/dpo_train.py --pairs-path data/training/dpo_pairs.jsonl

    # Dry run (build pairs only, don't train):
    python src/finetune/dpo_train.py --dry-run
"""

import argparse
import json
import logging
import os
import sys
from typing import Any, Dict, List, Optional

import torch
from datasets import Dataset

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
THIS_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(THIS_DIR, "..", ".."))
DEFAULT_PAIRS_PATH = os.path.join(PROJECT_ROOT, "data", "training", "dpo_pairs.jsonl")
DEFAULT_OUTPUT_DIR = os.path.join(PROJECT_ROOT, "results", "models", "dpo-lora")


# ===================================================================
# Data loading
# ===================================================================

def load_preference_pairs(path: str) -> List[Dict[str, Any]]:
    """Load DPO preference pairs from JSONL.

    Each line: ``{"prompt": ..., "chosen": ..., "rejected": ...}``
    """
    if not os.path.exists(path):
        logger.error("Preference pairs file not found: %s", path)
        return []

    pairs: List[Dict[str, Any]] = []
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                try:
                    pairs.append(json.loads(line))
                except json.JSONDecodeError as exc:
                    logger.warning("Skipping malformed pair: %s", exc)

    logger.info("Loaded %d preference pairs from %s", len(pairs), path)
    return pairs


# ===================================================================
# DPO Trainer
# ===================================================================

class DPOTrainerWrapper:
    """Wraps TRL's DPOTrainer for preference optimisation.

    Uses the same Unsloth base model loading as ``SupportFineTuner``
    in ``train.py`` but with a DPO head instead of SFT.
    """

    def __init__(self, config: Dict[str, Any]) -> None:
        self.config = config
        self.model = None
        self.tokenizer = None

    def load_base_model(self) -> None:
        """Load base model with 4-bit quantisation + LoRA."""
        try:
            from unsloth import FastLanguageModel
        except ImportError:
            logger.error(
                "unsloth not installed. Install with: "
                "pip install unsloth"
            )
            raise

        model_name = self.config.get(
            "base_model",
            "unsloth/Llama-3.1-8B-Instruct-bnb-4bit",
        )
        max_seq_length = self.config.get("max_seq_length", 2048)

        logger.info("Loading base model for DPO: %s", model_name)
        model, tokenizer = FastLanguageModel.from_pretrained(
            model_name=model_name,
            max_seq_length=max_seq_length,
            dtype=None,
            load_in_4bit=True,
            device_map="auto",
        )

        # Add LoRA adapters (same config as SFT)
        model = FastLanguageModel.get_peft_model(
            model,
            r=self.config.get("lora_r", 16),
            target_modules=[
                "q_proj", "k_proj", "v_proj", "o_proj",
                "gate_proj", "up_proj", "down_proj",
            ],
            lora_alpha=self.config.get("lora_alpha", 32),
            lora_dropout=0.0,
            bias="none",
            use_gradient_checkpointing="unsloth",
            random_state=3407,
            use_rslora=True,
            loftq_config=None,
        )

        self.model = model
        self.tokenizer = tokenizer
        logger.info(
            "DPO model loaded. Trainable params: %d",
            sum(p.numel() for p in model.parameters() if p.requires_grad),
        )

    def format_pairs(self, pairs: List[Dict[str, Any]]) -> Dataset:
        """Convert preference pairs to a DPO dataset.

        Each example has ``prompt``, ``chosen``, and ``rejected`` fields
        as required by ``DPOTrainer``.
        """
        prompts = []
        chosen_list = []
        rejected_list = []

        for pair in pairs:
            prompt = pair.get("prompt", "")
            chosen = pair.get("chosen", "")
            rejected = pair.get("rejected", "")
            if prompt and chosen and rejected:
                prompts.append(prompt)
                chosen_list.append(chosen)
                rejected_list.append(rejected)

        data = {
            "prompt": prompts,
            "chosen": chosen_list,
            "rejected": rejected_list,
        }
        dataset = Dataset.from_dict(data)
        logger.info("Formatted %d DPO examples", len(dataset))
        return dataset

    def train(self, dataset: Dataset) -> Any:
        """Run DPO training."""
        try:
            from trl import DPOTrainer, DPOConfig
        except ImportError:
            logger.error(
                "TRL not installed. Install with: pip install trl"
            )
            raise

        output_dir = self.config.get("output_dir", DEFAULT_OUTPUT_DIR)
        os.makedirs(output_dir, exist_ok=True)

        training_args = DPOConfig(
            output_dir=output_dir,
            per_device_train_batch_size=self.config.get("batch_size", 1),
            gradient_accumulation_steps=self.config.get("gradient_accumulation", 4),
            warmup_steps=self.config.get("warmup_steps", 5),
            max_steps=self.config.get("max_steps", 200),
            learning_rate=self.config.get("learning_rate", 1e-5),
            fp16=not torch.cuda.is_bf16_supported(),
            bf16=torch.cuda.is_bf16_supported(),
            optim="adamw_8bit",
            weight_decay=0.01,
            lr_scheduler_type="linear",
            seed=3407,
            logging_steps=10,
            save_steps=50,
            report_to="none",
            gradient_checkpointing=True,
            remove_unused_columns=False,
        )

        trainer = DPOTrainer(
            model=self.model,
            ref_model=None,  # uses the frozen base model internally
            tokenizer=self.tokenizer,
            train_dataset=dataset,
            args=training_args,
            max_length=self.config.get("max_seq_length", 2048),
            max_prompt_length=self.config.get("max_prompt_length", 1024),
        )

        logger.info("Starting DPO training...")
        trainer.train()
        logger.info("DPO training complete!")

        # Save
        save_path = self.config.get("save_path", DEFAULT_OUTPUT_DIR)
        self.model.save_pretrained(save_path)
        self.tokenizer.save_pretrained(save_path)
        logger.info("DPO model saved to %s", save_path)

        return trainer


# ===================================================================
# CLI
# ===================================================================

def main() -> None:
    parser = argparse.ArgumentParser(description="DPO fine-tuning from preference pairs")
    parser.add_argument("--pairs-path", type=str, default=DEFAULT_PAIRS_PATH)
    parser.add_argument("--base-model", type=str, default="unsloth/Llama-3.1-8B-Instruct-bnb-4bit")
    parser.add_argument("--output-dir", type=str, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--max-steps", type=int, default=200)
    parser.add_argument("--batch-size", type=int, default=1)
    parser.add_argument("--dry-run", action="store_true", help="Load & format pairs but don't train")
    args = parser.parse_args()

    config = {
        "base_model": args.base_model,
        "max_steps": args.max_steps,
        "batch_size": args.batch_size,
        "output_dir": args.output_dir,
        "save_path": args.output_dir,
        "max_seq_length": 2048,
        "max_prompt_length": 1024,
        "lora_r": 16,
        "lora_alpha": 32,
    }

    # Load preference pairs
    pairs = load_preference_pairs(args.pairs_path)
    if not pairs:
        print("No preference pairs found. Exiting.")
        sys.exit(0)

    if args.dry_run:
        print(f"Dry run: {len(pairs)} pairs ready for DPO training")
        print(f"  Prompt example: {pairs[0].get('prompt', '')[:100]}...")
        print(f"  Chosen example: {pairs[0].get('chosen', '')[:100]}...")
        print(f"  Rejected example: {pairs[0].get('rejected', '')[:100]}...")
        return

    # Load model
    trainer = DPOTrainerWrapper(config)
    try:
        trainer.load_base_model()
    except Exception as exc:
        print(f"Failed to load model: {exc}")
        print("DPO training requires GPU and unsloth. Skipping training.")
        sys.exit(1)

    # Format dataset
    dataset = trainer.format_pairs(pairs)

    # Train
    trainer.train(dataset)

    print(f"\n✓ DPO training complete!")
    print(f"  Model saved to: {args.output_dir}")


if __name__ == "__main__":
    main()
